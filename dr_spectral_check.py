r"""
DR + spectral + mastering checker (v2, merged 2026-08-24).

Per track:
  - DR14 dynamic range (TT DR Offline Meter algorithm, same as foobar2000 DR Meter)
  - Peak / RMS in dB, duration
  - PeakInt: the peak as a raw sample value in the file's own bit depth.
    Near-identical PeakInt across a whole album = brickwall limiter ceiling.
  - @Ceil / Run: samples pinned at the track peak and the longest unbroken
    run of them. A run of 3+ is flat-topped clipping.
  - Cutoff / Wall: where frequency content stops and how sharply (peak-hold
    spectrum). A cutoff that SPLITS into two groups across an album is the
    signature of a lossy transcode or fake upsample. An identical wall on
    every track is normal mastering-chain filtering.
  - >22k: for hi-res files, energy above 22.05 kHz relative to total.
    Around -60 dB or lower means upsampled 44.1 kHz, not true hi-res.

Per album folder it writes a permanent report, dr14.txt, INTO that folder,
with a plain-language diagnostics block (limiter ceiling / clipping /
transcode split / hi-res authenticity). It also saves this run's console
output to last_result.txt next to this script (overwritten each run), so
nothing is lost if the window closes early.

If an album trips the transcode or fake-hi-res checks, it ALSO renders a
spectrogram PNG per track into a spectrograms\ subfolder, so a doubtful
album arrives with the pictures already made. Clean albums get none.

Usage:
    drag a folder (or several) onto "DR Check - drag files here.bat"
    python dr_spectral_check.py "path\to\album folder" [more folders...]
    python dr_spectral_check.py "path\to\track.flac"      (print only, no report)
    python dr_spectral_check.py --no-write "folder"       (print only)
    python dr_spectral_check.py --spectrograms "folder"   (render them regardless)
    python dr_spectral_check.py --no-spectrograms "folder"   (never render them)

Artist/library folders are fine: every subfolder containing audio is
analysed as its own album and gets its own dr14.txt.

Needs: numpy. Uses its own private copy of ffmpeg.exe / ffprobe.exe in bin\
next to this script - deliberately NOT the AudioFakeDetector app's copy, so
this keeps working even if that app updates or gets replaced.
"""
import sys
import os
import math
import datetime
import subprocess
import numpy as np

if sys.stdout.encoding and sys.stdout.encoding.lower() != 'utf-8':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

HERE = os.path.dirname(os.path.abspath(__file__))
FFMPEG = os.path.join(HERE, "bin", "ffmpeg.exe")
FFPROBE = os.path.join(HERE, "bin", "ffprobe.exe")
AUDIO_EXT = ('.flac', '.wav', '.m4a', '.ape', '.wv', '.aiff', '.aif', '.ogg')

REPORT_NAME = 'dr14.txt'
SIGNATURE = 'generated by dr_spectral_check.py'

# A sample counts as "at the ceiling" within this fraction of the track's peak.
CEILING_TOL = 0.99999
# Track peaks within this many dB of each other count as a shared limiter ceiling.
SHARED_CEILING_DB = 0.05
# Cutoff frequencies further apart than this (Hz) get the transcode-split warning.
CUTOFF_SPLIT_HZ = 1500
# A 44.1 kHz file whose content stops below this, behind a steep wall, is very
# likely a lossy transcode dressed up as lossless - even if EVERY track does it
# (a wholly transcoded album has a consistent cutoff, so the split test misses it).
LOSSY_CUTOFF_HZ = 20000
LOSSY_WALL_DB = 30
# Loudness wording. A track above this RMS is "loud", but loud is not the same as
# compressed - the verdict also needs the DR value, which is level-independent.
# DR13+ genuinely dynamic, DR11-12 decent, DR9-10 compressed, DR8 and below crushed.
LOUD_RMS_DB = -14
CRUSHED_DR = 8
COMPRESSED_DR = 10
# Automatic spectrograms: rendered only for albums the checks flag as doubtful.
SPECTROGRAM_DIR = 'spectrograms'
SPECTROGRAM_SIZE = '1280x640'


def db(v):
    return 20 * math.log10(v) if v > 0 else float('-inf')


def fmt_db(v, width=9):
    return '-inf'.rjust(width) if v == float('-inf') else f'{v:{width}.2f}'


def fmt_dur(seconds):
    m, s = divmod(int(round(seconds)), 60)
    return f'{m}:{s:02d}'


def probe(path):
    r = subprocess.run(
        [FFPROBE, "-v", "error", "-select_streams", "a:0",
         "-show_entries", "stream=sample_rate,channels,bits_per_raw_sample",
         "-of", "csv=p=0", path],
        capture_output=True, text=True)
    parts = r.stdout.strip().split(",")
    sr, ch = int(parts[0]), int(parts[1])
    bits = None
    if len(parts) > 2 and parts[2].strip().isdigit():
        b = int(parts[2])
        if b in (8, 16, 24, 32):
            bits = b
    return sr, ch, bits


def decode_i32(path, sr, ch):
    """Decode to signed 32-bit ints (sub-32-bit depths arrive left-justified)."""
    r = subprocess.run(
        [FFMPEG, "-y", "-v", "error", "-i", path,
         "-f", "s32le", "-ar", str(sr), "-ac", str(ch), "pipe:1"],
        capture_output=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr.decode(errors="replace").strip())
    a = np.frombuffer(r.stdout, dtype=np.int32)
    n = len(a) // ch
    return a[:n * ch].reshape(n, ch)


def analyse_file(path):
    sr, ch, bits = probe(path)
    xi = decode_i32(path, sr, ch)
    x = xi.astype(np.float64) / 2.0 ** 31
    n, nch = x.shape
    if n < sr:  # under a second - not meaningfully analysable
        return None

    peak_int = None
    if bits:
        peak_int = int(np.max(np.abs(xi.astype(np.int64)))) >> (32 - bits)

    # --- DR14 ---
    blk = 3 * sr
    nblk = max(1, int(math.ceil(n / blk)))
    dr_ch, peak_ch, rms_ch = [], [], []
    for c in range(nch):
        s = x[:, c]
        rms_b = np.zeros(nblk)
        pk_b = np.zeros(nblk)
        for i in range(nblk):
            seg = s[i * blk:(i + 1) * blk]
            if seg.size == 0:
                continue
            rms_b[i] = math.sqrt(2.0 * np.mean(seg ** 2))
            pk_b[i] = np.max(np.abs(seg))
        pk_sorted = np.sort(pk_b)[::-1]
        peak2 = pk_sorted[1] if nblk > 1 else pk_sorted[0]
        n_top = max(1, int(0.2 * nblk))
        top = np.sort(rms_b)[::-1][:n_top]
        rms_upper = math.sqrt(np.sum(top ** 2) / n_top)
        dr_ch.append(db(peak2 / rms_upper) if rms_upper > 0 and peak2 > 0 else 0.0)
        peak_ch.append(float(np.max(np.abs(s))))
        rms_ch.append(math.sqrt(2.0 * np.mean(s ** 2)))

    peak = max(peak_ch)

    # --- ceiling / clipping ---
    at_ceiling = int(np.sum(np.abs(x) >= peak * CEILING_TOL))
    flat = np.abs(x[:, 0]) >= peak * CEILING_TOL
    edges = np.diff(np.concatenate(([0], flat.view(np.int8), [0])))
    starts = np.where(edges == 1)[0]
    ends = np.where(edges == -1)[0]
    longest_run = int(np.max(ends - starts)) if starts.size else 0

    # --- spectral wall (peak-hold over the middle 80% of the track) ---
    mono = x.mean(axis=1)
    win = 65536 if sr <= 48000 else 131072
    hop = win // 2
    start, end = int(n * 0.1), int(n * 0.9)
    freqs = np.fft.rfftfreq(win, d=1.0 / sr)
    hann = np.hanning(win)
    max_spec_db = None
    pos = start
    while pos + win <= end:
        seg = mono[pos:pos + win]
        if math.sqrt(np.mean(seg ** 2)) > 0.01:
            spec_db = 20 * np.log10(np.abs(np.fft.rfft(seg * hann)) + 1e-12)
            max_spec_db = spec_db if max_spec_db is None else np.maximum(max_spec_db, spec_db)
        pos += hop

    cutoff_freq, wall_drop = 0.0, 0.0
    if max_spec_db is not None:
        max_spec_db = max_spec_db - max_spec_db.max()
        idx = np.where(max_spec_db > -85)[0]
        if len(idx):
            cutoff_freq = float(freqs[idx[-1]])
        lo = max_spec_db[(freqs >= max(0, cutoff_freq - 1500)) & (freqs <= cutoff_freq - 500)]
        hi = max_spec_db[(freqs >= cutoff_freq + 500) & (freqs <= min(sr / 2, cutoff_freq + 1500))]
        if len(lo) and len(hi):
            wall_drop = float(lo.mean() - hi.mean())

    # --- ultrasonic share (hi-res authenticity) ---
    ultrasonic = None
    if sr > 44100:
        seg = x[:min(n, sr * 30), 0]
        if seg.size > 16:
            spec = np.abs(np.fft.rfft(seg * np.hanning(seg.size))) ** 2
            fr = np.fft.rfftfreq(seg.size, 1.0 / sr)
            total = spec.sum()
            high = spec[fr > 22050].sum()
            if total > 0:
                ultrasonic = db(math.sqrt(high / total)) if high > 0 else float('-inf')

    return {
        'file': os.path.basename(path),
        'dr': float(np.mean(dr_ch)),
        'peak_db': db(peak),
        'rms_db': db(math.sqrt(np.mean(np.array(rms_ch) ** 2))),
        'peak_int': peak_int,
        'at_ceiling': at_ceiling,
        'longest_run': longest_run,
        'cutoff': cutoff_freq,
        'wall_drop': wall_drop,
        'ultrasonic': ultrasonic,
        'duration': n / sr,
        'samplerate': sr,
        'channels': nch,
        'bits': bits,
    }


def diagnose(results):
    """Plain-language verdicts on limiting, clipping, transcodes and hi-res."""
    notes = []

    peaks = [r['peak_db'] for r in results if r['peak_db'] != float('-inf')]
    if len(peaks) >= 3:
        median_peak = float(np.median(peaks))
        shared = [p for p in peaks if abs(p - median_peak) <= SHARED_CEILING_DB]
        if len(shared) >= max(3, int(0.6 * len(peaks))):
            notes.append(
                f'Fixed ceiling: {len(shared)} of {len(peaks)} tracks peak at '
                f'{median_peak:.2f} dBFS (within {SHARED_CEILING_DB} dB).')
            notes.append('  Peaks this identical across different songs indicate an album-wide')
            notes.append('  brickwall limiter rather than a natural transfer.')
        else:
            notes.append(
                f'Peaks vary naturally across tracks ({min(peaks):.2f} to {max(peaks):.2f} dBFS) '
                '- no shared limiter ceiling.')

    clipped = [r for r in results if r['longest_run'] >= 3]
    if clipped:
        notes.append(f'Clipping: {len(clipped)} track(s) have flat-topped runs at the ceiling:')
        for r in clipped:
            notes.append(f'  {r["file"]} - longest run {r["longest_run"]} samples')
    else:
        notes.append('Clipping: none - no track has 3+ consecutive samples pinned at its peak.')

    cutoffs = [r['cutoff'] for r in results if r['cutoff'] > 0]

    # Work out the whole-album verdict first: a fully transcoded album has a
    # CONSISTENT cutoff, so the split test alone would call it clean.
    lossy = False
    med_cut = med_wall = 0.0
    if cutoffs:
        med_cut = float(np.median(cutoffs))
        walls = [r['wall_drop'] for r in results if r['cutoff'] > 0]
        med_wall = float(np.median(walls)) if walls else 0.0
        lossy = (results[0]['samplerate'] >= 44100
                 and med_cut < LOSSY_CUTOFF_HZ and med_wall > LOSSY_WALL_DB)

    if len(cutoffs) > 1:
        spread = max(cutoffs) - min(cutoffs)
        # small track-to-track wobble (a kHz or so) is normal - only flag a real split,
        # e.g. some tracks clean to ~24kHz and others walled off at ~20.5kHz (an actual
        # fake-copy case measured 20517-24000Hz, a 3.5kHz spread)
        if spread > CUTOFF_SPLIT_HZ:
            notes.append(
                f'Transcode check: spectral cutoff SPLITS into groups ({spread:.0f} Hz spread, '
                f'{min(cutoffs)/1000:.2f}-{max(cutoffs)/1000:.2f} kHz).')
            notes.append('  Worth a closer look - this is the pattern a lossy transcode or fake')
            notes.append('  upsample leaves. Tracks with the LOWER cutoff are the suspects.')
        elif lossy:
            notes.append(
                f'Transcode check: every track shares the same cutoff '
                f'(spread {spread:.0f} Hz) - so no single track stands out. See below.')
        else:
            notes.append(
                f'Transcode check: spectral cutoff is consistent across all tracks '
                f'(spread {spread:.0f} Hz) - normal for a genuine rip.')

    if lossy:
        notes.append(
            f'LOSSY SOURCE: content stops at {med_cut/1000:.2f} kHz behind a '
            f'{med_wall:.0f} dB wall, on every track.')
        notes.append('  A genuine CD rip runs to roughly 20.5-22 kHz. A hard wall this low')
        notes.append('  means the audio was lossy at some point and re-wrapped as lossless.')
        notes.append('  Rough guide: ~16 kHz = 128k mp3, ~19 kHz = 320k, ~20.5 kHz = V0/AAC.')

    hires = [r for r in results if r['ultrasonic'] is not None]
    if hires:
        vals = [r['ultrasonic'] for r in hires if r['ultrasonic'] != float('-inf')]
        if not vals:
            notes.append('Hi-res check: no content at all above 22.05 kHz - upsampled, not hi-res.')
        else:
            med = float(np.median(vals))
            if med < -60:
                notes.append(
                    f'Hi-res check: median energy above 22.05 kHz is {med:.1f} dB - effectively empty.')
                notes.append('  This looks like an upsampled 44.1 kHz source, not a true hi-res transfer.')
            else:
                notes.append(
                    f'Hi-res check: median energy above 22.05 kHz is {med:.1f} dB - genuine content present.')
                notes.append('  Consistent with a real high-rate or DSD source.')

    # RMS says how LOUD a file is, not how compressed it is - a dynamic master
    # normalised near 0 dBFS reads hot too. So only call it compressed when the
    # level-independent DR figure agrees, otherwise just report it as loud.
    loud = [r for r in results if r['rms_db'] > LOUD_RMS_DB]
    if loud:
        official = round(float(np.mean([r['dr'] for r in results])))
        head = f'Loudness: {len(loud)} of {len(results)} tracks above {LOUD_RMS_DB} dB RMS'
        if official <= CRUSHED_DR:
            notes.append(f'{head}, and album DR{official} - heavily compressed mastering.')
        elif official <= COMPRESSED_DR:
            notes.append(f'{head}, album DR{official} - a loud and fairly compressed master.')
        else:
            notes.append(f'{head}, but album DR{official} holds up - a loud master rather')
            notes.append('  than squashed dynamics. RMS is an absolute measure, so anything')
            notes.append('  normalised near 0 dBFS reads hot regardless; DR is the one to trust.')

    return notes


def suspicion(results):
    """Why this album deserves a look at its spectrograms, or None if it looks fine."""
    cutoffs = [r['cutoff'] for r in results if r['cutoff'] > 0]

    if len(cutoffs) > 1:
        spread = max(cutoffs) - min(cutoffs)
        if spread > CUTOFF_SPLIT_HZ:
            return (f'spectral cutoff splits across the album '
                    f'({min(cutoffs)/1000:.2f}-{max(cutoffs)/1000:.2f} kHz)')

    if cutoffs:
        med_cut = float(np.median(cutoffs))
        walls = [r['wall_drop'] for r in results if r['cutoff'] > 0]
        med_wall = float(np.median(walls)) if walls else 0.0
        if results[0]['samplerate'] >= 44100 and med_cut < LOSSY_CUTOFF_HZ and med_wall > LOSSY_WALL_DB:
            return f'content walled off at {med_cut/1000:.2f} kHz - lossy source'

    vals = [r['ultrasonic'] for r in results
            if r['ultrasonic'] is not None and r['ultrasonic'] != float('-inf')]
    if any(r['ultrasonic'] is not None for r in results):
        if not vals:
            return 'hi-res file with nothing at all above 22.05 kHz'
        if float(np.median(vals)) < -60:
            return (f'hi-res file with near-empty content above 22.05 kHz '
                    f'({float(np.median(vals)):.1f} dB)')

    return None


def render_spectrograms(folder, results):
    """Write a spectrogram PNG per track into a subfolder of the album.

    Uses the bundled ffmpeg, so this needs nothing installed. Returns the
    output folder on success, or None if nothing could be written.
    """
    out_dir = os.path.join(folder, SPECTROGRAM_DIR)
    try:
        os.makedirs(out_dir, exist_ok=True)
    except OSError as exc:
        print(f'  !! could not create {SPECTROGRAM_DIR} folder: {exc}')
        return None

    made = 0
    for r in results:
        src = os.path.join(folder, r['file'])
        dst = os.path.join(out_dir, os.path.splitext(r['file'])[0] + '.png')
        try:
            proc = subprocess.run(
                [FFMPEG, '-y', '-v', 'error', '-i', src,
                 '-lavfi', f'showspectrumpic=s={SPECTROGRAM_SIZE}:mode=combined:legend=1',
                 dst],
                capture_output=True)
            if proc.returncode == 0:
                made += 1
            else:
                print(f'  !! spectrogram failed for {r["file"]}: '
                      f'{proc.stderr.decode(errors="replace").strip()[:120]}')
        except OSError as exc:
            print(f'  !! spectrogram failed for {r["file"]}: {exc}')

    if not made:
        return None
    print(f'  -> {made} spectrogram(s) written to {out_dir}')
    return out_dir


def build_report(folder, results, spec_dir=None):
    width = 132
    rule = '-' * width
    out = []
    out.append(rule)
    out.append(f' Analyzed folder: {folder}')
    out.append(rule)
    out.append('')
    out.append(f"{' DR':<7}{'Peak':>12}{'RMS':>12}{'Duration':>10}{'PeakInt':>12}"
               f"{'@Ceil':>8}{'Run':>6}{'Cutoff':>10}{'Wall':>8}{'>22k':>8}   Track")
    out.append(rule)

    for r in results:
        peak_int = '-' if r['peak_int'] is None else f"{r['peak_int']}"
        ultra = 'n/a' if r['ultrasonic'] is None else f"{r['ultrasonic']:.1f}"
        cutoff = f"{r['cutoff']/1000:.2f}k" if r['cutoff'] > 0 else '-'
        wall = f"{r['wall_drop']:.0f}dB" if r['cutoff'] > 0 else '-'
        out.append(
            f" DR{round(r['dr']):<4}"
            f"{fmt_db(r['peak_db'])} dB"
            f"{fmt_db(r['rms_db'])} dB"
            f"{fmt_dur(r['duration']):>10}"
            f"{peak_int:>12}"
            f"{r['at_ceiling']:>8}"
            f"{r['longest_run']:>6}"
            f"{cutoff:>10}"
            f"{wall:>8}"
            f"{ultra:>8}   "
            f"{r['file']}")

    out.append(rule)
    out.append('')

    mean_dr = float(np.mean([r['dr'] for r in results]))
    first = results[0]
    out.append(f" Number of tracks:  {len(results)}")
    out.append(f" Official DR value: DR{round(mean_dr)}      (mean of track DR = {mean_dr:.2f})")
    out.append('')
    out.append(f" Samplerate:        {first['samplerate']} Hz")
    out.append(f" Channels:          {first['channels']}")
    out.append(f" Bits per sample:   {first['bits'] if first['bits'] else '-'}")
    out.append('')
    out.append(rule)
    out.append(' Diagnostics')
    out.append(rule)
    for note in diagnose(results):
        out.append(f' {note}')

    if spec_dir:
        out.append('')
        out.append(' Spectrograms were rendered because the checks above flagged this album.')
        out.append(f' One PNG per track, in the {SPECTROGRAM_DIR}\\ subfolder.')
        out.append(' Look at the top edge of each image: a genuine lossless rip fades out')
        out.append(' naturally near the top, while a hard flat shelf with blackness above it')
        out.append(' means the audio was lossy at some point. If only SOME tracks show the')
        out.append(' shelf, those tracks are the problem rather than the whole album.')

    out.append('')
    out.append(' Columns: PeakInt = peak as a raw sample value in the file\'s own bit depth.')
    out.append('          @Ceil = samples sitting at the track peak. Run = longest unbroken run')
    out.append('          of them (>=3 means flat-topped clipping). Cutoff/Wall = where the')
    out.append('          spectrum stops and how sharply. >22k = energy above 22.05 kHz vs')
    out.append('          total, in dB (hi-res files only).')
    out.append('')
    out.append(f' DR14 algorithm, {SIGNATURE} on '
               f'{datetime.datetime.now().strftime("%Y-%m-%d %H:%M")}')
    out.append(rule)
    return '\n'.join(out) + '\n'


def write_report(folder, text):
    path = os.path.join(folder, REPORT_NAME)
    # Never silently destroy a report this script did not write.
    if os.path.exists(path):
        try:
            existing = open(path, encoding='utf-8', errors='replace').read()
        except OSError:
            existing = ''
        if SIGNATURE not in existing and 'generated by dr14.py' not in existing:
            backup = path + '.bak'
            if not os.path.exists(backup):
                os.replace(path, backup)
                print(f'  ! existing {REPORT_NAME} was not ours - kept as {os.path.basename(backup)}')
    with open(path, 'w', encoding='utf-8', newline='\r\n') as fh:
        fh.write(text)
    return path


def album_folders(root):
    found = []
    for dirpath, _, filenames in os.walk(root):
        if any(f.lower().endswith(AUDIO_EXT) for f in filenames):
            found.append(dirpath)
    return sorted(found)


def process_folder(folder, write=True, spectrograms='auto'):
    names = sorted(f for f in os.listdir(folder) if f.lower().endswith(AUDIO_EXT))
    print(f'\n=== {folder}')
    results = []
    for name in names:
        try:
            r = analyse_file(os.path.join(folder, name))
        except Exception as exc:
            print(f'  !! {name}: {exc}')
            continue
        if r is None:
            print(f'  -- {name}: too short to analyse')
            continue
        results.append(r)
        print(f"  DR{round(r['dr']):<3} {fmt_db(r['peak_db'], 7)} dB {fmt_db(r['rms_db'], 7)} dB"
              f"  cutoff {r['cutoff']/1000:5.2f}k   {name}")

    if not results:
        print('  no analysable audio')
        return

    mean_dr = float(np.mean([r['dr'] for r in results]))
    print(f'  Official DR value: DR{round(mean_dr)}  (mean {mean_dr:.2f}, {len(results)} tracks)')
    for note in diagnose(results):
        print(f'  {note}')

    spec_dir = None
    if spectrograms != 'never':
        reason = suspicion(results)
        if spectrograms == 'always' or reason:
            if reason:
                print(f'  Rendering spectrograms - flagged because {reason}.')
            else:
                print('  Rendering spectrograms (asked for on every album).')
            spec_dir = render_spectrograms(folder, results)

    if not write:
        return
    try:
        path = write_report(folder, build_report(folder, results, spec_dir))
        print(f'  -> report written to {path}')
    except OSError as exc:
        print(f'  !! could not write report into the album folder: {exc}')
        print('     (results are still in last_result.txt next to the script)')


class _Tee:
    """Echo everything printed to the console into a buffer for the log file."""

    def __init__(self, stream):
        self.stream = stream
        self.buf = []

    def write(self, s):
        self.stream.write(s)
        self.buf.append(s)

    def flush(self):
        self.stream.flush()


def write_run_log(text):
    """Save this run's console output beside the script, as UTF-8 with a BOM so
    Notepad renders accented track names correctly."""
    try:
        with open(os.path.join(HERE, 'last_result.txt'), 'w',
                  encoding='utf-8-sig', newline='\r\n') as fh:
            fh.write(text)
    except OSError:
        pass  # a read-only stick is not a reason to lose the run


def main(argv):
    write = True
    spectrograms = 'auto'
    targets = []
    for a in argv:
        if a == '--no-write':
            write = False
        elif a == '--spectrograms':
            spectrograms = 'always'
        elif a == '--no-spectrograms':
            spectrograms = 'never'
        elif a in ('-h', '--help'):
            print(__doc__)
            return 0
        else:
            targets.append(a.strip().strip('"').strip("'"))

    if not targets:
        print(__doc__)
        return 1

    for target in targets:
        target = os.path.abspath(target)
        if os.path.isfile(target):
            # single dragged track: print analysis, no report
            print(f'\n=== {target}')
            try:
                r = analyse_file(target)
            except Exception as exc:
                print(f'  !! {exc}')
                continue
            if r is None:
                print('  too short to analyse')
                continue
            ultra = 'n/a' if r['ultrasonic'] is None else f"{r['ultrasonic']:.1f} dB"
            print(f"  DR{round(r['dr'])}   peak {fmt_db(r['peak_db'],7)} dB   rms {fmt_db(r['rms_db'],7)} dB"
                  f"   cutoff {r['cutoff']/1000:.2f} kHz (wall {r['wall_drop']:.0f} dB)   >22k {ultra}")
        elif os.path.isdir(target):
            for folder in album_folders(target):
                process_folder(folder, write=write, spectrograms=spectrograms)
        else:
            print(f'\n!! not found: {target}')
    return 0


if __name__ == '__main__':
    _tee = _Tee(sys.stdout)
    sys.stdout = _tee
    try:
        code = main(sys.argv[1:])
    except Exception:
        import traceback
        print('\nUNEXPECTED ERROR:')
        traceback.print_exc(file=sys.stdout)
        code = 1
    finally:
        sys.stdout = _tee.stream
        write_run_log(''.join(_tee.buf))
    sys.exit(code)
